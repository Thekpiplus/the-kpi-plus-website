function walk(path) {
  const stat = statSync(path);
  if (stat.isDirectory()) {
    for (const name of readdirSync(path)) walk(join(path, name));
    return;
  }
  if (!/\.(ts|tsx|css|mjs)$/.test(path)) return;
  let text = readFileSync(path, "utf8");
  const original = text;
  for (const [from, to] of pairs) text = text.split(from).join(to);
  if (text !== original) writeFileSync(path, text);
}

function renameCss() {
  const from = join("components/meta-ops/ads-ops.css");
  const to = join("components/meta-ops/meta-ops.css");
  try {
    renameSync(from, to);
  } catch {
    // already renamed
  }
}

